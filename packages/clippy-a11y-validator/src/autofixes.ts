import type { Validation } from './types/validation.ts';

export type AutofixableSolutions = Record<string, { rule: string; solutionIds: string[] }>;

export type AutofixesJson = Record<string, AutofixableSolutions[string] | string> & { $comment: string };

/**
 * Per rule in `@nl-design-system-unstable/documentation`, keyed by its id, the solutions a correction
 * of the validator carries out. Published as `autofixes.json` so the documentation can mark them.
 */
export const autofixableSolutions = (validations: readonly Validation[]): AutofixableSolutions =>
  Object.fromEntries(
    validations.flatMap(({ corrections, documentationId, rule }) => {
      const solutionIds = [
        ...new Set((corrections ?? []).flatMap(({ solutionId }) => (solutionId === undefined ? [] : [solutionId]))),
      ].sort((a, b) => a.localeCompare(b));

      return documentationId === undefined || solutionIds.length === 0
        ? []
        : [[documentationId, { rule, solutionIds }]];
    }),
  );

/**
 * The contents of `autofixes.json`: the autofixable solutions with a `$comment` on what they are, as
 * the documentation's own JSON explains itself.
 */
export const autofixesJson = (validations: readonly Validation[]): AutofixesJson => ({
  $comment:
    'Generated by @nl-design-system-community/clippy-a11y-validator. Keyed by the id of a rule in @nl-design-system-unstable/documentation: the validator rule that checks it, and the ids of the solutions to that rule a correction of the validator carries out automatically. Every key but this $comment is a rule id.',
  ...autofixableSolutions(validations),
});
